"""Build the default (Classic) launcher icon from the painted artwork in tools/voidx-icon.jpeg.

Outputs: drawable-nodpi/ic_launcher_art.png (adaptive-icon foreground, full bleed), the legacy
mipmap app_icon.png / app_icon_alt.png, the README icons, the brand pill's mark (the heart cut out,
ic_voidx_mark_art) and the Android 12+ launch animation (the cut-out heart beating twice:
voidx_splash_f*.webp frames played by drawable/voidx_splash_beat.xml). The artwork's own dark ground fills
the whole 108-unit layer; its edges are feathered into GROUND so no seam shows where it ends.
The themed-icon (monochrome) layer still comes from tools/render_icon.py.
Usage: python tools/icon_from_image.py
"""
import pathlib

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "smarttubetv" / "src" / "stmobile" / "res"
SRC = ROOT / "tools" / "voidx-icon.jpeg"
GROUND = (3, 1, 7)  # the artwork's corner colour
LAYER = 864  # 108 units at 8 px each: sharp on any launcher scale
ART = 0.72  # artwork width / layer width; its heart (2/3 of the art) then spans ~48% of the layer


def foreground():
    art = Image.open(SRC).convert("RGB")
    size = round(LAYER * ART)
    art = art.resize((size, size), Image.LANCZOS)
    feather = Image.new("L", (size, size), 0)
    edge = size // 10
    ImageDraw.Draw(feather).rectangle([edge, edge, size - edge, size - edge], fill=255)
    feather = feather.filter(ImageFilter.GaussianBlur(edge / 2))
    layer = Image.new("RGB", (LAYER, LAYER), GROUND)
    off = (LAYER - size) // 2
    layer.paste(art, (off, off), feather)
    return layer


def heart():
    """The heart alone on transparency: its red body (play triangle filled back in), soft edged."""
    art = Image.open(SRC).convert("RGB")
    r, g, b = art.split()
    body = Image.eval(r, lambda v: 255 if v > 150 else 0)
    redder = ImageChops.subtract(r, g)  # the glow and the dark ground are not red enough
    mask = ImageChops.multiply(body, Image.eval(redder, lambda v: 255 if v > 60 else 0))
    filled = mask.copy()
    ImageDraw.floodfill(filled, (0, 0), 128)  # outside the heart; everything else is heart
    mask = Image.eval(filled, lambda v: 0 if v == 128 else 255).filter(ImageFilter.GaussianBlur(1.5))
    cut = art.convert("RGBA")
    cut.putalpha(mask)
    return cut.crop(mask.getbbox())


def square(img, px, fill):
    """img centred in a transparent px square, scaled so its longer side is fill * px."""
    scale = fill * px / max(img.size)
    img = img.resize((round(img.size[0] * scale), round(img.size[1] * scale)), Image.LANCZOS)
    canvas = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    canvas.paste(img, ((px - img.size[0]) // 2, (px - img.size[1]) // 2), img)
    return canvas


# Lub-dub: two beats, the second stronger, then rest (the splash holds the last frame).
BEAT = [1.0, 1.05, 1.1, 1.05, 1.0, 1.07, 1.14, 1.07, 1.0]
BEAT_MS = 60


def splash(out):
    cut = heart()
    items = []
    for i, scale in enumerate(BEAT):
        # The splash icon is 240dp with a 160dp visible circle: the heart stays inside it.
        square(cut, 384, 0.44 * scale).save(out / f"voidx_splash_f{i}.webp", quality=90)
        items.append(f'    <item android:drawable="@drawable/voidx_splash_f{i}" android:duration="{BEAT_MS}" />')
    xml = "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- VOIDXDEV(launch): generated by tools/icon_from_image.py - the new icon's heart beating. -->",
        '<animation-list xmlns:android="http://schemas.android.com/apk/res/android" android:oneshot="true">',
        *items,
        "</animation-list>",
        ""])
    (RES / "drawable" / "voidx_splash_beat.xml").write_text(xml, encoding="utf-8")


def legacy(px):
    """Pre-26 launchers: the artwork in a rounded square, like render_icon.py's PNGs."""
    art = Image.open(SRC).convert("RGB").resize((px, px), Image.LANCZOS).convert("RGBA")
    mask = Image.new("L", (px * 4, px * 4), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, px * 4 - 1, px * 4 - 1], radius=px * 4 * 0.23,
                                           fill=255)
    art.putalpha(mask.resize((px, px), Image.LANCZOS))
    return art


def main():
    out = RES / "drawable-nodpi"
    out.mkdir(exist_ok=True)
    foreground().save(out / "ic_launcher_art.png", optimize=True)
    for density, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144),
                        ("xxxhdpi", 192)):
        icon = legacy(px)
        for name in ("app_icon.png", "app_icon_alt.png"):
            icon.save(RES / f"mipmap-{density}" / name)
    legacy(512).save(ROOT / ".github" / "assets" / "icon.png")
    legacy(256).save(ROOT / ".github" / "assets" / "voidx" / "icon.png")
    square(heart(), 192, 1.0).save(out / "ic_voidx_mark_art.png", optimize=True)
    splash(out)


if __name__ == "__main__":
    main()
